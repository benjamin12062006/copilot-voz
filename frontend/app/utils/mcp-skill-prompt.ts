    '```json',
    '{',
    '  "copilot-voz": {',
    '    "command": "/Users/benji/.local/bin/uv",',
    '    "args": [',
    '      "--directory",',
    '      "/Users/benji/Documents/Copilot/backend",',
    '      "run",',
    '      "--locked",',
    '      "python",',
    '      "-m",',
    '      "app.mcp_server"',
