    '- **Qué hace el servidor MCP (`copilot-voz`):** Es un adaptador `stdio` ligero (`backend/app/mcp_server.py`) que expone **una única herramienta**:',
    '  - `voice_submit_document(title: str, markdown: str, idempotency_key: str)`',
    '  - Envía el documento Markdown a FastAPI (`POST /api/v1/agent/documents`) con `Authorization: Bearer <COPILOT_MCP_API_TOKEN>`.',
    '  - Guarda el documento para escucharlo en la interfaz web; no reproduce audio por sí solo.',
